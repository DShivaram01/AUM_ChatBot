"""Show how a document is chunked (same code path as DocumentService.ingest).

    python scripts/dump_chunks.py FILE [FILE ...] [--out chunks.md]
    python scripts/dump_chunks.py --fixtures --out docs/chunks/eval_fixture_chunks.md

Each chunk prints its heading path, page span, size and full text, i.e. what
retrieval embeds and what the answer/quiz prompts see (answers trim each chunk
to 500 chars -- marked below). Nothing is embedded or sent to a model.
"""

import argparse
import json
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from ingestion.document_parser import document_format, extract_pages, extract_pdf_pages, structured_chunks  # noqa: E402

PROMPT_CHARS = 500  # core/assistant_service.py _trunc(hit["text"], 500)


def chunk_file(name: str, content: bytes) -> tuple[list[dict], int]:
    kind, _mime = document_format(name, content)
    if kind == "pdf":
        with tempfile.NamedTemporaryFile(suffix=".pdf") as f:
            f.write(content); f.flush()
            pages = extract_pdf_pages(Path(f.name))
        return structured_chunks(pages), len(pages)
    pages, headings = extract_pages(kind, content)
    return structured_chunks(pages, headings=headings), len(pages)


def render(name: str, chunks: list[dict], n_pages: int) -> str:
    sizes = [len(c["text"]) for c in chunks]
    out = [f"## {name}", "",
           f"{n_pages} page(s) -> {len(chunks)} chunk(s); chars min/median/max = "
           f"{min(sizes)}/{sorted(sizes)[len(sizes) // 2]}/{max(sizes)}; "
           f"{sum(s > PROMPT_CHARS for s in sizes)} chunk(s) exceed the {PROMPT_CHARS}-char prompt view", ""]
    for i, c in enumerate(chunks):
        pages = f"p.{c['page']}" if c["page"] == c["page_end"] else f"p.{c['page']}-{c['page_end']}"
        path = " > ".join(c["heading_path"]) or "(no heading)"
        cut = f", prompt sees first {PROMPT_CHARS}" if len(c["text"]) > PROMPT_CHARS else ""
        out += [f"### chunk {i}  |  {pages}  |  {path}  |  {len(c['text'])} chars{cut}", "", "```text", c["text"], "```", ""]
    return "\n".join(out)


def fixture_pdfs() -> list[tuple[str, bytes]]:
    sys.path.insert(0, str(ROOT / "scripts"))
    from eval_document_quiz import build_pdf
    spec = json.loads((ROOT / "tests/fixtures/document_qa_eval.json").read_text())
    return [(d["filename"], build_pdf(d["pages"])) for d in spec["documents"]]


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("files", nargs="*")
    ap.add_argument("--fixtures", action="store_true", help="the 3 fictional evaluation PDFs")
    ap.add_argument("--out")
    a = ap.parse_args()
    docs = [(Path(f).name, Path(f).read_bytes()) for f in a.files]
    if a.fixtures:
        docs += fixture_pdfs()
    if not docs:
        ap.error("give FILE(s) or --fixtures")
    text = "# Chunk dump\n\nGenerated by `scripts/dump_chunks.py` (same chunker as ingestion: heading/page-aware, ~400 regex tokens).\n\n"
    text += "\n".join(render(n, *chunk_file(n, c)) for n, c in docs)
    if a.out:
        Path(a.out).parent.mkdir(parents=True, exist_ok=True)
        Path(a.out).write_text(text)
        print(f"wrote {a.out}")
    else:
        print(text)


if __name__ == "__main__":
    main()
